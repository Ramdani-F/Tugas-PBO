
public class Increment {
        public static void tampilkan() {
        int a = 5;
        System.out.println("Nilai awal a = " + a);

        System.out.println("Post-increment (a++) = " + a++);
        System.out.println("Nilai a setelah a++ = " + a);

        System.out.println("Pre-increment (++a) = " + ++a);
        System.out.println("Nilai a setelah ++a = " + a);
    }
    
}
